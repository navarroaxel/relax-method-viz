function parseCsv(csv: string): Float64Array {
  const parts = csv.split(",");
  const out = new Float64Array(parts.length);
  for (let k = 0; k < parts.length; k++) out[k] = Number(parts[k]);
  return out;
}

/** Force channel F_A1, in mN, one sample every {@link STEP_DT_S}. */
export const stepForceMn: Float64Array = parseCsv(STEP_FORCE_MN_CSV);

/** Current channel I_B1, in A, sampled alongside {@link stepForceMn}. */
export const stepCurrentA: Float64Array = parseCsv(STEP_CURRENT_A_CSV);

/** Sample index -> time in seconds. */
export function stepTime(index: number): number {
  return index * STEP_DT_S;
}

export interface StepAnalysis {
  /** Mean force over the last fifth of the record, in mN. */
  forceSteadyMn: number;
  /** Mean current over the same window, in A. */
  currentSteadyA: number;
  /** Largest force sample, in mN, and when it happened, in s. */
  peakMn: number;
  peakTimeS: number;
  /** Overshoot above the steady value, in percent. */
  overshootPct: number;
  /** Time at which the current channel first reaches 99 % of its plateau. */
  currentSettledS: number;
  /** Times at which the force first crosses 10 / 90 % of steady state, in s. */
  t10S: number;
  t90S: number;
  /** 10 % to 90 % rise time, in s. */
  riseTimeS: number;
  /** Last time the force is outside +/-2 % of steady state, in s. */
  settlingTimeS: number;
  /** Damping ratio of the equivalent 2nd-order system, from the overshoot. */
  zeta: number;
  /** Undamped natural frequency of that system, in Hz. */
  naturalFreqHz: number;
  /** Slope a = F/I^2 at the plateau, in mN/A^2. */
  slopeMnPerA2: number;
  /** mu0 from that plateau, ideal two-wire model, in H/m. */
  mu0IdealHPerM: number;
  /** mu0 from the same plateau with the loop return conductors kept in. */
  mu0CorrectedHPerM: number;
  /** Guide 2.2 error budget evaluated at the plateau. */
  error: ErrorTerms;
}

function mean(a: Float64Array, from: number, to: number): number {
  let s = 0;
  for (let k = from; k < to; k++) s += a[k] ?? 0;
  return s / (to - from);
}

/** First time `signal` reaches `target`, or the record length if it never does. */
function firstCrossing(signal: Float64Array, target: number): number {
  for (let k = 0; k < signal.length; k++) {
    if ((signal[k] ?? 0) >= target) return stepTime(k);
  }
  return stepTime(signal.length - 1);
}

/**
 * Step-response figures of merit, plus the mu0 the plateau implies.
 *
 * The 2nd-order identification is the same one Laboratorio 1 uses: the
 * overshoot fixes zeta, and the time from the current's arrival to the force
 * peak (t_p = pi/w_d) then fixes w_n. It is a model of the sensor, not of the
 * physics — but it is the model that says how long to wait.
 */
export function analyzeStep(
  force: Float64Array = stepForceMn,
  current: Float64Array = stepCurrentA,
  separationM = SEPARATION_M,
  lengthM = FORCE_LENGTH_M,
): StepAnalysis {
  const n = force.length;
  const tailFrom = Math.floor(n * 0.8);
  const forceSteadyMn = mean(force, tailFrom, n);
  const currentSteadyA = mean(current, tailFrom, n);

  let peakMn = force[0] ?? 0;
  let peakIndex = 0;
  for (let k = 1; k < n; k++) {
    if ((force[k] ?? 0) > peakMn) {
      peakMn = force[k] ?? 0;
      peakIndex = k;
    }
  }
  const overshootPct = ((peakMn - forceSteadyMn) / forceSteadyMn) * 100;

  const currentSettledS = firstCrossing(current, 0.99 * currentSteadyA);
  const t10S = firstCrossing(force, 0.1 * forceSteadyMn);
  const t90S = firstCrossing(force, 0.9 * forceSteadyMn);

  const band = 0.02 * forceSteadyMn;
  let settlingTimeS = 0;
  for (let k = n - 1; k >= 0; k--) {
    if (Math.abs((force[k] ?? 0) - forceSteadyMn) > band) {
      settlingTimeS = stepTime(Math.min(k + 1, n - 1));
      break;
    }
  }

  const m = Math.max(overshootPct / 100, 1e-6);
  const lnM = Math.log(m);
  const zeta = -lnM / Math.sqrt(Math.PI * Math.PI + lnM * lnM);
  const peakTimeS = stepTime(peakIndex);
  const tp = Math.max(peakTimeS - currentSettledS, STEP_DT_S);
  const wn = Math.PI / (tp * Math.sqrt(1 - zeta * zeta));

  const slopeMnPerA2 = forceSteadyMn / (currentSteadyA * currentSteadyA);
  const factor = geometryFactor(separationM);

  return {
    forceSteadyMn,
    currentSteadyA,
    peakMn,
    peakTimeS,
    overshootPct,
    currentSettledS,
    t10S,
    t90S,
    riseTimeS: t90S - t10S,
    settlingTimeS,
    zeta,
    naturalFreqHz: wn / (2 * Math.PI),
    slopeMnPerA2,
    mu0IdealHPerM: (2 * Math.PI * separationM * slopeMnPerA2 * 1e-3) / lengthM,
    mu0CorrectedHPerM:
      (2 * Math.PI * slopeMnPerA2 * 1e-3) / (lengthM * factor.factorPerM),
    error: errorTerms(currentSteadyA, forceSteadyMn, separationM, lengthM),
  };
}
