function parseCsv(csv: string): Float64Array {
  const parts = csv.split(",");
  const out = new Float64Array(parts.length);
  for (let k = 0; k < parts.length; k++) out[k] = Number(parts[k]);
  return out;
}

/** Force channel F_A1, in mN, one sample every {@link ESCALON_DT_S}. */
export const escalonForceMn: Float64Array = parseCsv(FORCE_MN_CSV);

/** Current channel I_B1, in A, sampled alongside {@link escalonForceMn}. */
export const escalonCurrentA: Float64Array = parseCsv(CURRENT_A_CSV);

/** Sample index → time in seconds. */
export function escalonTime(index: number): number {
  return index * ESCALON_DT_S;
}

export interface StepAnalysis {
  /** Mean of the force channel over the last 20 % of the record, in mN. */
  forceSteadyMn: number;
  /** Mean of the current channel over the same window, in A. */
  currentSteadyA: number;
  /** Largest force sample and when it happened. */
  peakMn: number;
  peakTimeS: number;
  /** Overshoot above the steady value, in percent. */
  overshootPct: number;
  /** First time the force leaves the pre-step noise band. */
  onsetS: number;
  /** Times at which the force first crosses 10 / 50 / 90 % of steady state. */
  t10S: number;
  t50S: number;
  t90S: number;
  /** 10 %→90 % rise time, in seconds. */
  riseTimeS: number;
  /** Last time the force is outside ±2 % of steady state, in seconds. */
  settlingTimeS: number;
  /** Damping ratio of the equivalent 2nd-order system, from the overshoot. */
  zeta: number;
  /** Undamped natural frequency of that system, in Hz. */
  naturalFreqHz: number;
  /** B = F / (I · l) evaluated at steady state, in mT. */
  fieldMt: number;
  /** See {@link effectiveDelayS}. */
  effectiveDelayS: number;
}

/**
 * The delay this sensor adds to a slowly varying input: the centroid of its
 * impulse response, which for a step response s(t) with plateau s∞ works out
 * to ∫(s∞ − s(t)) dt / s∞ — the area between the response and its own
 * plateau, divided by the plateau.
 *
 * Unlike the rise or settling time this needs no model of the system, and it
 * is the number that turns up as lag when the input is a ramp rather than a
 * step. It is also much shorter than either: most of the settling happens
 * close to the final value, where it barely shifts the centroid.
 */
export function effectiveDelayS(
  force: Float64Array,
  steadyMn: number,
  dtS = ESCALON_DT_S,
): number {
  if (steadyMn === 0) return 0;
  let area = 0;
  for (let k = 0; k < force.length; k++) area += steadyMn - (force[k] ?? 0);
  return (area * dtS) / steadyMn;
}

function mean(a: Float64Array, from: number, to: number): number {
  let s = 0;
  for (let k = from; k < to; k++) s += a[k] ?? 0;
  return s / (to - from);
}

/** First time `signal` reaches `target`, or the record length if it never does. */
function firstCrossing(signal: Float64Array, target: number): number {
  for (let k = 0; k < signal.length; k++) {
    if ((signal[k] ?? 0) >= target) return escalonTime(k);
  }
  return escalonTime(signal.length - 1);
}

/**
 * Extract the classic step-response figures of merit from the escalón capture.
 * `force` is in mN and `current` in A; both must be the same length and
 * sampled at {@link ESCALON_DT_S}.
 */
export function analyzeStep(
  force: Float64Array,
  current: Float64Array,
  loopLengthM = LOOP_LENGTH_M,
): StepAnalysis {
  const n = force.length;
  const tailFrom = Math.floor(n * 0.8);
  const forceSteadyMn = mean(force, tailFrom, n);
  const currentSteadyA = mean(current, tailFrom, n);

  let peakMn = force[0] ?? 0;
  let peakIndex = 0;
  for (let k = 1; k < n; k++) {
    if ((force[k] ?? 0) > peakMn) {
      peakMn = force[k] ?? 0;
      peakIndex = k;
    }
  }
  const overshootPct = ((peakMn - forceSteadyMn) / forceSteadyMn) * 100;

  // Pre-step samples are pure sensor noise; the response has "started" once
  // the signal clears three times the largest noise excursion.
  const preSteps = Math.min(40, n);
  let noise = 0;
  for (let k = 0; k < preSteps; k++)
    noise = Math.max(noise, Math.abs(force[k] ?? 0));
  const onsetS = firstCrossing(force, 3 * noise);

  const t10S = firstCrossing(force, 0.1 * forceSteadyMn);
  const t50S = firstCrossing(force, 0.5 * forceSteadyMn);
  const t90S = firstCrossing(force, 0.9 * forceSteadyMn);

  const band = 0.02 * forceSteadyMn;
  let settlingTimeS = 0;
  for (let k = n - 1; k >= 0; k--) {
    if (Math.abs((force[k] ?? 0) - forceSteadyMn) > band) {
      settlingTimeS = escalonTime(Math.min(k + 1, n - 1));
      break;
    }
  }

  // Underdamped 2nd-order identification: the overshoot fixes ζ, and the time
  // from onset to the peak (t_p = π / ω_d) then fixes ω_n.
  const m = Math.max(overshootPct / 100, 1e-6);
  const lnM = Math.log(m);
  const zeta = -lnM / Math.sqrt(Math.PI * Math.PI + lnM * lnM);
  const peakTimeS = escalonTime(peakIndex);
  const tp = Math.max(peakTimeS - onsetS, ESCALON_DT_S);
  const wn = Math.PI / (tp * Math.sqrt(1 - zeta * zeta));

  // F in mN and B in mT share the 1e-3 factor, so B[mT] = F[mN] / (I · l).
  const fieldMt = forceSteadyMn / (currentSteadyA * loopLengthM);

  return {
    forceSteadyMn,
    currentSteadyA,
    peakMn,
    peakTimeS,
    overshootPct,
    onsetS,
    t10S,
    t50S,
    t90S,
    riseTimeS: t90S - t10S,
    settlingTimeS,
    zeta,
    naturalFreqHz: wn / (2 * Math.PI),
    fieldMt,
    effectiveDelayS: effectiveDelayS(force, forceSteadyMn),
  };
}

/**
 * Instantaneous B = F / (I · l) in mT for every sample. Only meaningful once
 * the current has reached its plateau — before that the ratio is dominated by
 * the sensor lag, which is exactly what makes it worth plotting.
 */
export function fieldSeriesMt(
  force: Float64Array,
  current: Float64Array,
  loopLengthM = LOOP_LENGTH_M,
): Float64Array {
  const out = new Float64Array(force.length);
  for (let k = 0; k < force.length; k++) {
    const i = current[k] ?? 0;
    out[k] = Math.abs(i) < 1e-6 ? 0 : (force[k] ?? 0) / (i * loopLengthM);
  }
  return out;
}
